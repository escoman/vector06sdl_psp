/* Glyph for a character, or nullptr when the character is not in the
 * font. Lowercase letters map onto their uppercase glyphs. */
static inline const uint8_t * overlay_font_glyph(char c)
{
    if (c >= 'a' && c <= 'z') {
        c = (char)(c - 'a' + 'A');
    }
    if (c >= 'A' && c <= 'Z') {
        return overlay_font[c - 'A'];
    }
    if (c >= '0' && c <= '9') {
        return overlay_font[26 + (c - '0')];
    }
    if (c == ':') {
        return overlay_font[36];
    }
    if (c == ' ') {
        return overlay_font[37];
    }
    return nullptr;
}
